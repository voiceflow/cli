import { randomUUID } from 'node:crypto';

import { describe, expect } from 'vitest';

import { $vf, isDateString, sequential, setupProjectTest } from './utils';

const ENVIRONMENT_DEFAULTS = {
  isMain: false,
  trafficPercentage: 0,
  createdAt: expect.toSatisfy(isDateString),
  releases: [
    {
      name: 'First version',
      backupID: expect.any(Number),
      description: 'Cloned from Main',
      autogenerated: false,
      createdAt: expect.toSatisfy(isDateString),
    },
  ],
};

describe('vf environment', () => {
  const project = setupProjectTest();

  const $vf_environment: typeof $vf = (args, options) =>
    $vf([`--project-id=${project().id}`, 'environment', ...args], options);

  describe('CRUD', { concurrent: false }, () => {
    const it = sequential();
    let environment1: any;
    let environment2: any;
    let environment3: any;

    it('clone with args', async () => {
      const name = 'environment from args';
      const alias = `environment_${randomUUID().replaceAll('-', '_')}`;
      ({ environment: environment1 } = await $vf_environment([
        'clone',
        `--name=${name}`,
        `--alias=${alias}`,
        '--environment-alias=main',
      ]));

      expect(environment1).toEqual({ ...ENVIRONMENT_DEFAULTS, name, alias });
    });

    it('clone with body', async () => {
      const name = 'environment from body';
      const alias = `environment_${randomUUID().replaceAll('-', '_')}`;
      ({ environment: environment2 } = await $vf_environment([
        'clone',
        '--environment-alias=main',
        `--body=${JSON.stringify({ name, alias })}`,
      ]));

      expect(environment2).toEqual({ ...ENVIRONMENT_DEFAULTS, name, alias });
    });

    it('clone with stdin', async () => {
      const name = 'environment from stdin';
      const alias = `environment_${randomUUID().replaceAll('-', '_')}`;
      ({ environment: environment3 } = await $vf_environment(['clone', '--environment-alias=main'], {
        stdin: 'pipe',
        input: JSON.stringify({ name, alias }),
      }));

      expect(environment3).toEqual({ ...ENVIRONMENT_DEFAULTS, name, alias });
    });

    it('update with args', async () => {
      const result = await $vf_environment([
        'update',
        `--environment-alias=${environment1.alias}`,
        '--name=renamed with args',
      ]);

      expect(result).toEqual({ message: `Environment ${environment1.alias} updated.` });
    });

    it('update with body', async () => {
      const result = await $vf_environment([
        'update',
        `--environment-alias=${environment2.alias}`,
        `--body=${JSON.stringify({ name: 'renamed with body' })}`,
      ]);

      expect(result).toEqual({ message: `Environment ${environment2.alias} updated.` });
    });

    it('update with stdin', async () => {
      const result = await $vf_environment(['update', `--environment-alias=${environment3.alias}`], {
        stdin: 'pipe',
        input: JSON.stringify({ name: 'renamed with stdin' }),
      });

      expect(result).toEqual({ message: `Environment ${environment3.alias} updated.` });
    });

    it('get', async () => {
      const result = await $vf_environment(['get', `--environment-alias=${environment1.alias}`]);

      expect(result).toEqual({
        environment: expect.objectContaining({ alias: environment1.alias, name: 'renamed with args' }),
      });
    });

    it('merge', async () => {
      const result = await $vf_environment([
        'merge',
        `--source-environment-alias=${environment2.alias}`,
        `--target-environment-alias=${environment3.alias}`,
        `--remove-source-environment=true`,
      ]);

      expect(result).toEqual({
        sourceEnvironment: expect.objectContaining({ alias: environment2.alias }),
        targetEnvironment: expect.objectContaining({ alias: environment3.alias }),
        targetRelease: {
          name: 'V1.00',
          backupID: expect.any(Number),
          autogenerated: false,
          createdAt: expect.toSatisfy(isDateString),
          description: 'Merged from renamed with body',
        },
      });
    });

    it('compile', async () => {
      const result = await $vf_environment(['compile', `--environment-alias=${environment1.alias}`]);

      expect(result).toEqual({
        message: `Environment ${environment1.alias} compiled.`,
        durationMs: expect.any(Number),
      });
    });

    it('publish', async () => {
      const name = 'release name';
      const result = await $vf_environment(['publish', `--environment-alias=${environment1.alias}`, `--name=${name}`]);

      expect(result).toEqual({
        environment: expect.objectContaining({ alias: environment1.alias }),
        release: {
          name,
          backupID: expect.any(Number),
          description: null,
          autogenerated: false,
          createdAt: expect.toSatisfy(isDateString),
        },
      });
    });

    it('delete', async () => {
      const result = await $vf_environment(['delete', `--environment-alias=${environment1.alias}`]);

      expect(result).toEqual({ message: `Environment ${environment1.alias} deleted.` });
    });

    it('list', async () => {
      const result = await $vf_environment(['list']);

      expect(result).toEqual({
        environments: expect.not.arrayContaining([
          expect.objectContaining({ alias: environment1.alias }),
          expect.objectContaining({ alias: environment2.alias }),
        ]),
      });
      expect(result).toEqual({
        environments: expect.arrayContaining([
          expect.objectContaining({ alias: 'main' }),
          expect.objectContaining({ alias: environment3.alias }),
        ]),
      });
    });
  });
});
