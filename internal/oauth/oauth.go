// Package oauth implements browser-based OAuth 2.0 login for the CLI.
//
// The flow is the authorization code grant with PKCE (RFC 7636) and a loopback
// redirect (RFC 8252), which is what the Voiceflow authorization server
// advertises at https://auth-api.voiceflow.com/.well-known/oauth-authorization-server:
// response type "code", challenge method "S256", token endpoint auth method
// "none" (a public client with no secret), and dynamic client registration
// (RFC 7591). The authorization endpoint additionally requires an RFC 8707
// "resource" indicator naming the API the token is for.
//
// Tokens are stored in the OS keychain (macOS Keychain, Windows Credential
// Manager, Linux Secret Service) through internal/config, with an owner-only
// file beside the CLI config as the fallback for machines without one.
//
// This package is hand-written and is not regenerated by Speakeasy. The
// generated commands call into it at four points: auth login, auth logout,
// whoami, and client construction.
package oauth

import (
	"context"
	"errors"
	"fmt"
	"io"
	"net"
	"net/http"
	"net/url"
	"strconv"
	"strings"
	"sync"
	"time"
)

const (
	// DefaultIssuer is the Voiceflow authorization server.
	DefaultIssuer = "https://auth-api.voiceflow.com"
	// DefaultResource is the RFC 8707 resource indicator: the API the issued
	// access token is intended for. It matches the SDK's default server.
	DefaultResource = "https://realtime-api.voiceflow.com"
	// clientName is what the authorization server shows on the consent screen.
	clientName = "Voiceflow CLI"
	// callbackPath is the loopback path the browser is redirected to.
	callbackPath = "/oauth/callback"

	// DefaultLoginTimeout bounds how long login waits for the browser.
	DefaultLoginTimeout = 5 * time.Minute
	// refreshWindow refreshes an access token this long before it expires,
	// so a request is never sent with a token that expires mid-flight.
	refreshWindow = 60 * time.Second
)

// Environment overrides, mainly for non-production authorization servers.
const (
	envIssuer      = "VF_OAUTH_ISSUER"
	envClientID    = "VF_OAUTH_CLIENT_ID"
	envResource    = "VF_OAUTH_RESOURCE"
	envScopes      = "VF_OAUTH_SCOPES"
	envRedirectURI = "VF_OAUTH_REDIRECT_URI"
)

// defaultScopes is used when the authorization server does not advertise its
// scopes and the caller did not ask for specific ones.
var defaultScopes = []string{"universal.workspace.read", "universal.workspace.write"}

// callbackPorts are the loopback ports the client registers redirect URIs for.
// Several are registered so a port already taken by another process (or a
// second concurrent login) does not block the flow.
var callbackPorts = []int{51330, 51331, 51332, 51333}

// httpClient is the client used for all authorization server calls. It is a
// package variable so tests can point it at an httptest server.
var httpClient = &http.Client{Timeout: 30 * time.Second}

// refreshMu serialises token refreshes within a process.
var refreshMu sync.Mutex

// redirectTarget is a loopback redirect URI split into its parts, so the
// listener address and the URI string always stay in sync.
type redirectTarget struct {
	Host string
	Port int
	Path string
}

func (r redirectTarget) address() string {
	return net.JoinHostPort(r.Host, strconv.Itoa(r.Port))
}

func (r redirectTarget) uri() string {
	return "http://" + r.address() + r.Path
}

// parseRedirectTarget parses a loopback redirect URI previously registered
// with the authorization server.
func parseRedirectTarget(raw string) (redirectTarget, error) {
	u, err := url.Parse(raw)
	if err != nil {
		return redirectTarget{}, fmt.Errorf("parse redirect URI %q: %w", raw, err)
	}
	if u.Scheme != "http" {
		return redirectTarget{}, fmt.Errorf("redirect URI %q is not a loopback http URI", raw)
	}
	host := u.Hostname()
	if host != "127.0.0.1" && host != "localhost" && host != "::1" {
		return redirectTarget{}, fmt.Errorf("redirect URI %q is not a loopback address", raw)
	}
	port, err := strconv.Atoi(u.Port())
	if err != nil {
		return redirectTarget{}, fmt.Errorf("redirect URI %q has no port", raw)
	}
	path := u.Path
	if path == "" {
		path = "/"
	}
	return redirectTarget{Host: host, Port: port, Path: path}, nil
}

// settings resolves the issuer, resource, and any pre-registered client from
// the environment.
type settings struct {
	Issuer      string
	ClientID    string
	Resource    string
	RedirectURI string
	Scopes      []string
}

func settingsFromEnv(getenv func(string) string) settings {
	s := settings{
		Issuer:      strings.TrimSuffix(firstNonEmpty(getenv(envIssuer), DefaultIssuer), "/"),
		ClientID:    getenv(envClientID),
		Resource:    firstNonEmpty(getenv(envResource), DefaultResource),
		RedirectURI: getenv(envRedirectURI),
	}
	if raw := getenv(envScopes); raw != "" {
		s.Scopes = strings.Fields(strings.ReplaceAll(raw, ",", " "))
	}
	return s
}

func firstNonEmpty(values ...string) string {
	for _, v := range values {
		if v != "" {
			return v
		}
	}
	return ""
}

// LoginOptions configures a login attempt.
type LoginOptions struct {
	// Scopes requested at the authorization endpoint. Empty means the scopes
	// the server advertises, falling back to defaultScopes.
	Scopes []string
	// NoBrowser prints the authorization URL instead of opening a browser,
	// for SSH sessions and machines without a desktop.
	NoBrowser bool
	// Timeout bounds the wait for the browser redirect. Zero means
	// DefaultLoginTimeout.
	Timeout time.Duration
	// Out receives progress messages. Nil discards them.
	Out io.Writer
}

// Login runs the authorization code flow and stores the resulting session.
func Login(ctx context.Context, getenv func(string) string, opts LoginOptions) (*Session, error) {
	out := opts.Out
	if out == nil {
		out = io.Discard
	}
	timeout := opts.Timeout
	if timeout <= 0 {
		timeout = DefaultLoginTimeout
	}

	cfg := settingsFromEnv(getenv)

	md, err := discover(ctx, httpClient, cfg.Issuer)
	if err != nil {
		if md.TokenEndpoint == "" {
			return nil, fmt.Errorf("discover authorization server: %w", err)
		}
		fmt.Fprintf(out, "Warning: could not read authorization server metadata (%v); using known endpoints.\n", err)
	}
	if !md.supportsS256() {
		return nil, fmt.Errorf("authorization server at %s does not support PKCE S256", md.Issuer)
	}

	client, err := resolveClient(ctx, md, cfg)
	if err != nil {
		return nil, err
	}

	state, err := randomURLSafe(32)
	if err != nil {
		return nil, err
	}
	verifier, err := newPKCE()
	if err != nil {
		return nil, err
	}

	callback, client, err := listen(ctx, md, cfg, client, state)
	if err != nil {
		return nil, err
	}
	defer callback.Close()

	scopes := opts.Scopes
	if len(scopes) == 0 {
		scopes = cfg.Scopes
	}
	if len(scopes) == 0 {
		scopes = md.ScopesSupported
	}
	if len(scopes) == 0 {
		scopes = defaultScopes
	}

	authURL := authorizationURL(md, client.ClientID, callback.RedirectURI(), state, verifier.challenge, scopes, cfg.Resource)

	if opts.NoBrowser {
		fmt.Fprintf(out, "Open this URL to sign in:\n\n  %s\n\n", authURL)
	} else if err := browserOpener(authURL); err != nil {
		fmt.Fprintf(out, "Could not open a browser (%v).\nOpen this URL to sign in:\n\n  %s\n\n", err, authURL)
	} else {
		fmt.Fprintf(out, "Opening your browser to sign in.\nIf it did not open, use this URL:\n\n  %s\n\n", authURL)
	}
	fmt.Fprintln(out, "Waiting for the browser to complete sign-in...")

	waitCtx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()

	code, err := callback.Wait(waitCtx)
	if err != nil {
		if errors.Is(err, context.DeadlineExceeded) {
			return nil, fmt.Errorf("timed out after %s waiting for the browser to complete sign-in", timeout)
		}
		return nil, err
	}

	tok, err := exchangeCode(ctx, httpClient, md, client.ClientID, code, verifier.verifier, callback.RedirectURI(), cfg.Resource)
	if err != nil {
		return nil, fmt.Errorf("exchange authorization code: %w", err)
	}

	now := time.Now()
	session := &Session{
		Issuer:        md.Issuer,
		TokenEndpoint: md.TokenEndpoint,
		ClientID:      client.ClientID,
		Resource:      cfg.Resource,
		Scope:         firstNonEmpty(tok.Scope, strings.Join(scopes, " ")),
		TokenType:     firstNonEmpty(tok.TokenType, "Bearer"),
		Expiry:        tok.expiry(now),
		ObtainedAt:    now,
		AccessToken:   tok.AccessToken,
		RefreshToken:  tok.RefreshToken,
	}
	if err := SaveSession(session); err != nil {
		return nil, fmt.Errorf("store session: %w", err)
	}
	return session, nil
}

// resolveClient returns the OAuth client to authorize with: an explicitly
// configured one, the cached dynamic registration, or a fresh registration.
func resolveClient(ctx context.Context, md Metadata, cfg settings) (*clientRecord, error) {
	if cfg.ClientID != "" {
		redirectURIs := []string{cfg.RedirectURI}
		if cfg.RedirectURI == "" {
			redirectURIs = defaultRedirectURIs()
		}
		return &clientRecord{Issuer: md.Issuer, ClientID: cfg.ClientID, RedirectURIs: redirectURIs}, nil
	}

	cached, err := loadClient(md.Issuer)
	if err != nil {
		return nil, err
	}
	if cached != nil && len(cached.RedirectURIs) > 0 {
		return cached, nil
	}

	registered, err := registerClient(ctx, httpClient, md, clientName, defaultRedirectURIs())
	if err != nil {
		return nil, err
	}
	if err := saveClient(registered); err != nil {
		return nil, fmt.Errorf("cache client registration: %w", err)
	}
	return registered, nil
}

func defaultRedirectURIs() []string {
	uris := make([]string, 0, len(callbackPorts))
	for _, port := range callbackPorts {
		uris = append(uris, redirectTarget{Host: "127.0.0.1", Port: port, Path: callbackPath}.uri())
	}
	return uris
}

// listen starts the loopback receiver on one of the client's registered
// redirect URIs. If every registered port is busy it registers a new client on
// an ephemeral port, since the authorization server rejects a redirect URI the
// client is not registered for.
func listen(ctx context.Context, md Metadata, cfg settings, client *clientRecord, state string) (*callbackServer, *clientRecord, error) {
	targets := make([]redirectTarget, 0, len(client.RedirectURIs))
	for _, raw := range client.RedirectURIs {
		target, err := parseRedirectTarget(raw)
		if err != nil {
			continue // a non-loopback URI cannot host the receiver
		}
		targets = append(targets, target)
	}
	if len(targets) == 0 {
		return nil, nil, fmt.Errorf("client %s has no loopback redirect URI to listen on", client.ClientID)
	}

	callback, err := startCallbackServer(targets, state)
	if err == nil {
		return callback, client, nil
	}
	if cfg.ClientID != "" {
		// A pre-registered client cannot have new redirect URIs added here.
		return nil, nil, err
	}

	// Ephemeral port, then register that exact URI.
	callback, ephemeralErr := startCallbackServer([]redirectTarget{{Host: "127.0.0.1", Port: 0, Path: callbackPath}}, state)
	if ephemeralErr != nil {
		return nil, nil, fmt.Errorf("%w (and no ephemeral port was available: %v)", err, ephemeralErr)
	}

	registered, regErr := registerClient(ctx, httpClient, md, clientName, append(defaultRedirectURIs(), callback.RedirectURI()))
	if regErr != nil {
		callback.Close()
		return nil, nil, regErr
	}
	if err := saveClient(registered); err != nil {
		callback.Close()
		return nil, nil, fmt.Errorf("cache client registration: %w", err)
	}
	return callback, registered, nil
}

func authorizationURL(md Metadata, clientID, redirectURI, state, challenge string, scopes []string, resource string) string {
	params := url.Values{
		"response_type":         {"code"},
		"client_id":             {clientID},
		"redirect_uri":          {redirectURI},
		"state":                 {state},
		"code_challenge":        {challenge},
		"code_challenge_method": {"S256"},
	}
	if len(scopes) > 0 {
		params.Set("scope", strings.Join(scopes, " "))
	}
	if resource != "" {
		// RFC 8707: the authorization server requires the audience the token
		// is being requested for.
		params.Set("resource", resource)
	}

	separator := "?"
	if strings.Contains(md.AuthorizationEndpoint, "?") {
		separator = "&"
	}
	return md.AuthorizationEndpoint + separator + params.Encode()
}

// AccessToken returns a valid access token for the stored session, refreshing
// it when it is expired or about to expire. It returns ErrNoSession when the
// user is not logged in.
func AccessToken(ctx context.Context) (string, error) {
	refreshMu.Lock()
	defer refreshMu.Unlock()

	session, err := LoadSession()
	if err != nil {
		return "", err
	}

	now := time.Now()
	if !session.needsRefresh(now) {
		return session.AccessToken, nil
	}
	if session.RefreshToken == "" {
		_ = ClearSession()
		return "", fmt.Errorf("OAuth session expired; run 'vf auth login'")
	}

	tok, err := refreshTokens(ctx, httpClient, session.TokenEndpoint, session.ClientID, session.RefreshToken, session.Scope, session.Resource)
	if err != nil {
		var tokErr *tokenError
		if errors.As(err, &tokErr) && tokErr.isInvalidGrant() {
			_ = ClearSession()
			return "", fmt.Errorf("OAuth session is no longer valid; run 'vf auth login'")
		}
		// A transient failure should not break a command whose token is still
		// inside its lifetime.
		if !session.expired(now) {
			return session.AccessToken, nil
		}
		return "", fmt.Errorf("refresh OAuth session: %w", err)
	}

	session.AccessToken = tok.AccessToken
	if tok.RefreshToken != "" {
		// The server rotates refresh tokens; keep the previous one otherwise.
		session.RefreshToken = tok.RefreshToken
	}
	if tok.Scope != "" {
		session.Scope = tok.Scope
	}
	if tok.TokenType != "" {
		session.TokenType = tok.TokenType
	}
	session.Expiry = tok.expiry(now)
	session.ObtainedAt = now

	// A refreshed token that could not be persisted is still usable for this
	// command, so a storage failure must not fail the request.
	_ = SaveSession(session)
	return session.AccessToken, nil
}

// needsRefresh reports whether the access token is expired or close enough to
// expiry to be refreshed first. A session with no known expiry is used as is.
func (s *Session) needsRefresh(now time.Time) bool {
	if s.AccessToken == "" {
		return true
	}
	if s.Expiry.IsZero() {
		return false
	}
	return now.After(s.Expiry.Add(-refreshWindow))
}

func (s *Session) expired(now time.Time) bool {
	return !s.Expiry.IsZero() && now.After(s.Expiry)
}

// Logout clears the stored session. The authorization server publishes no
// revocation endpoint, so this removes the local credentials only.
func Logout() error {
	return ClearSession()
}

// Status describes the stored session for 'vf auth whoami'.
type Status struct {
	LoggedIn bool
	Issuer   string
	ClientID string
	Scope    string
	Storage  string
	Expiry   time.Time
	Expired  bool
}

// CurrentStatus reports the stored session without refreshing it.
func CurrentStatus() Status {
	session, err := LoadSession()
	if err != nil || session == nil {
		return Status{}
	}
	return Status{
		LoggedIn: true,
		Issuer:   session.Issuer,
		ClientID: session.ClientID,
		Scope:    session.Scope,
		Storage:  session.storageLocation(),
		Expiry:   session.Expiry,
		Expired:  session.expired(time.Now()),
	}
}
